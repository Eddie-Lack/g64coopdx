#!/usr/bin/env python3
"""Writes src/client/bankranges_table.c: the game's bank switch as a table, for programs that do not link the game.

The game finds a bank's ROM range in TextureBankRange and ObjectBankRange (weemitt/src/game/banks.c). Each case
names two ROM symbols. A symbol's address is in the game's code, as a "lui" and an "addiu" or "ori" pair, and
weemitt reads it from the ROM at start-up (port_set_rom_symbols, weemitt/src/port/loaders.c). Its table of those
pairs is weemitt/gen/romsyms.c. This script joins the two. The table holds bank numbers and offsets of the game's
code only, no bytes of the ROM.

tests/rom/rombanks.c compares the table with the game's own switch (G64BankRom) on the player's ROM.

Usage: python3 tools/gen_bankranges.py (from the repository's top folder).
"""
import re
import sys

BANKS = "weemitt/src/game/banks.c"
ENUMS = "weemitt/include/enums.h"
ROMSYMS = "weemitt/gen/romsyms.c"
OUT = "src/client/bankranges_table.c"


def tex_enum():
    text = open(ENUMS).read()
    body = re.search(r"enum TexBank \{(.*?)\};", text, re.S).group(1)
    values, n = {}, 0
    for item in body.split(","):
        item = item.strip()
        if not item:
            continue
        if "=" in item:
            name, v = [x.strip() for x in item.split("=")]
            n = int(v, 0)
        else:
            name = item
        values[name] = n
        n += 1
    return values


def switch(text, fn, enum):
    body = re.search(fn + r"\(u32 num, u32 \*start, u32 \*end\) \{\s*switch \(num\) \{(.*?)\n    \}", text, re.S)
    cases = []
    for m in re.finditer(r"case (\w+):\s*\*start = PORT_ROM_ADDR\((\w+)\);\s*\*end = PORT_ROM_ADDR\((\w+)\);",
                         body.group(1)):
        num = int(m.group(1)) if m.group(1).isdigit() else enum[m.group(1)]
        cases.append((num, m.group(2), m.group(3)))
    if not cases:
        sys.exit("no cases found in " + fn)
    return sorted(cases)


def romsyms():
    syms = {}
    for m in re.finditer(r"\{ \(void \*\*\)&port_rom_(\w+), (0x[0-9a-f]+), (0x[0-9a-f]+|0), (0x[0-9a-f]+|0) \}",
                         open(ROMSYMS).read()):
        syms[m.group(1)] = tuple(int(x, 0) for x in m.group(2, 3, 4))
    return syms


def main():
    text = open(BANKS).read()
    syms = romsyms()
    kinds = [switch(text, "TextureBankRange", tex_enum()), switch(text, "ObjectBankRange", {})]
    out = [
        "/* Generated by tools/gen_bankranges.py from weemitt's src/game/banks.c and gen/romsyms.c. Do not edit. */",
        '#include "bankranges.h"',
        "",
        "const G64BankRangeEntry g64_bank_ranges[2][G64_BANK_RANGES_MAX] = {",
    ]
    counts = []
    for kind in kinds:
        out.append("    {")
        for num, start, end in kind:
            a, b = syms[start], syms[end]
            out.append("        {%d, {0x%08x, 0x%x, 0x%x}, {0x%08x, 0x%x, 0x%x}}, /* %s, %s */"
                       % (num, a[0], a[1], a[2], b[0], b[1], b[2], start, end))
        out.append("    },")
        counts.append(len(kind))
    out.append("};")
    out.append("const unsigned g64_bank_range_count[2] = {%d, %d};" % tuple(counts))
    if max(counts) > 64:
        sys.exit("more banks than G64_BANK_RANGES_MAX")
    open(OUT, "w").write("\n".join(out) + "\n")


main()
